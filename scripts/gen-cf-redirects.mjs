// Generate dist/_redirects for Cloudflare Pages.
// - Converts vercel.json redirects (all 301)
// - Adds 302 redirects for pages excluded from the CF build back to main site.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const MAIN = 'https://twobears.vercel.app';

// Pages excluded from the CF build (must match build-cf.mjs)
const EXCLUDED_PAGES = [
  'cruise', 'hotels', 'food', 'omikuji', 'oracle', 'biggsgpt',
  'member', 'travel-news', 'friends', 'fortune', 'pick', 'picks', 'language',
];
const EXCLUDED_DIR_PATHS = ['/admin/*', '/keystatic/*', '/tools/*', '/api/*'];

export function buildRedirectLines() {
  const vj = JSON.parse(readFileSync(resolve('vercel.json'), 'utf-8'));
  const lines = [];
  lines.push('# Auto-generated by scripts/gen-cf-redirects.mjs — do not edit.');
  lines.push('');
  lines.push('# --- Excluded interactive pages -> main site (302) ---');
  for (const p of EXCLUDED_PAGES) {
    lines.push(`/${p}   ${MAIN}/${p}   302`);
  }
  for (const p of EXCLUDED_DIR_PATHS) {
    // splat forwarding, preserve remainder
    const dest = `${MAIN}${p.replace('/*', '/:splat')}`;
    lines.push(`${p}   ${dest}   302`);
  }
  lines.push('');
  lines.push(`# --- Vercel.json redirects (${(vj.redirects || []).length} × 301) ---`);
  for (const r of vj.redirects || []) {
    lines.push(`${r.source}   ${r.destination}   ${r.permanent ? 301 : 302}`);
  }
  return lines;
}

export function totalRedirectCount() {
  const vj = JSON.parse(readFileSync(resolve('vercel.json'), 'utf-8'));
  return (vj.redirects || []).length + EXCLUDED_PAGES.length + EXCLUDED_DIR_PATHS.length;
}

export function writeRedirects(distDir = 'dist') {
  const lines = buildRedirectLines();
  writeFileSync(resolve(distDir, '_redirects'), lines.join('\n') + '\n', 'utf-8');
  return lines.length;
}

// CLI usage
if (import.meta.url === `file://${process.argv[1]}`) {
  const n = writeRedirects();
  console.log(`[gen-cf-redirects] Wrote ${n} lines, total redirect rules: ${totalRedirectCount()}`);
}
